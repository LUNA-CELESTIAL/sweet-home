"""Run one full day with real Ollama generation (still no Discord).

Morning duty -> Ping session -> evening duty -> diary -> site export,
all generated by the real model, printed and saved under out/.
This is the Step 4 integration check on the real machine.

Usage: python3 sim/run_real_day.py   (needs .env with OLLAMA_MODEL)
"""

import datetime
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
from config import load_env  # noqa: E402
from diary import build_diary, writer_for  # noqa: E402
from duty import duty_member  # noqa: E402
from export_site import build_entry, merge  # noqa: E402
from generate import diary_prose, duty_text  # noqa: E402
from llm import OllamaClient  # noqa: E402
from session import run_session  # noqa: E402

DATE = datetime.date(2026, 11, 23)
YESTERDAY_SEED = {
    "topic": "Pingツール", "sourceMember": "ステラ",
    "quote": "機能の数だけ手を出すのではなく、静かな回線の中で本当に必要なものを選ぶ目配り",
    "note": "ステラのPingツールの話、途中で終わっていたのが気になってる。",
}
EVENTS = [
    {"minutes": 9 * 60, "member": "こはく", "topic": "朝の当番"},
    {"minutes": 10 * 60 + 30, "member": "スピカ", "topic": "Pingツールの続き", "open": True,
     "quote": "実際に小さなパケットを放って、どの往復だけが返るか測ってみようかな"},
    {"minutes": 15 * 60, "member": "ルナ", "topic": "実生成の会話が初めて成立した", "kind": "home"},
]


def main():
    env_path = ROOT / ".env"
    if not env_path.exists():
        print("No .env yet. Run: cp .env.example .env, then set OLLAMA_MODEL.")
        return
    cfg = load_env(env_path)
    try:
        llm = OllamaClient(cfg.get("OLLAMA_BASE_URL", "http://localhost:11434"),
                           cfg.get("OLLAMA_MODEL", ""))
    except ValueError as e:
        print(f"Cannot start: {e}")
        return

    morning_member = duty_member(DATE, "morning")
    morning = duty_text(llm, morning_member, "morning", "晴れ", YESTERDAY_SEED)
    print(f"[morning duty / {morning_member['name']}] {morning}\n")

    transcript, pool_line = run_session(YESTERDAY_SEED, ["luna", "stella", "spica", "stella"], llm)
    for t in transcript:
        print(f"[{t['name']}] {t['text']}")
    print(f"({pool_line})\n")

    evening_member = duty_member(DATE, "evening")
    evening = duty_text(llm, evening_member, "evening", "", None)
    print(f"[evening duty / {evening_member['name']}] {evening}\n")

    writer = writer_for(DATE)
    structure, _ = build_diary(DATE, EVENTS)
    meta, md = diary_prose(llm, writer, DATE, EVENTS, structure)
    print(md)

    out = ROOT / "out"
    out.mkdir(exist_ok=True)
    (out / "diary-2026-11-23.md").write_text(md, encoding="utf-8")
    (out / "diary-2026-11-23.json").write_text(
        json.dumps(meta, ensure_ascii=False, indent=1), encoding="utf-8")
    site_path = ROOT / "export" / "diary.json"
    existing = json.loads(site_path.read_text(encoding="utf-8")) if site_path.exists() else None
    site = merge(existing, build_entry(meta, md))
    (out / "diary-site.json").write_text(json.dumps(site, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"saved: out/diary-2026-11-23.md / .json / diary-site.json (seed: {meta['seed']})")


if __name__ == "__main__":
    main()
